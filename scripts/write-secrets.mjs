// Writes src/secrets.ts from build variables, so Cloudflare's Git build (Workers Builds) can bundle the secrets
// without them ever being in git (the repo is public) or in the Worker's runtime variables.
//
// Runs as wrangler's custom build (wrangler.jsonc -> build.command), before bundling, on every `wrangler deploy`/`dev`.
//   - In Cloudflare's build (WORKERS_CI=1): src/secrets.ts is (re)written from the build variables below.
//   - Locally: an existing src/secrets.ts is never touched. If it is missing, the same variables are used if set,
//     otherwise the build stops with a clear message.
// Never prints a value, only variable names.
import { existsSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const target = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "secrets.ts");
const REQUIRED = ["DIDAR_CLIENT_ID", "DIDAR_CLIENT_SECRET", "ENCRYPTION_KEY"];
const OPTIONAL = ["DIDAR_INSTALLATION_URL"];
const inCi = !!process.env.WORKERS_CI;

if (!inCi && existsSync(target)) {
  console.log("[secrets] using the existing src/secrets.ts");
  process.exit(0);
}

const missing = REQUIRED.filter((k) => !process.env[k]);
if (missing.length) {
  // Diagnostics, names only: variables that look like ours (typo, wrong case, extra spaces) or are set but empty.
  const norm = (k) => k.toUpperCase().replace(/[^A-Z]/g, "");
  const wanted = new Set([...REQUIRED, ...OPTIONAL].map(norm));
  const similar = Object.keys(process.env)
    .filter((k) => !REQUIRED.includes(k) && (wanted.has(norm(k)) || /DIDAR|ENCRYPT|CLIENT/i.test(k)))
    .map((k) => JSON.stringify(k));
  const empty = REQUIRED.filter((k) => k in process.env && !process.env[k]);
  console.error(
    `[secrets] cannot create src/secrets.ts: missing ${missing.join(", ")}.\n` +
      (empty.length ? `  Set but empty: ${empty.join(", ")}.\n` : "") +
      (similar.length ? `  Similar names that ARE set (check spelling/spaces): ${similar.join(", ")}.\n` : "") +
      (inCi
        ? "  Add them in Cloudflare -> Workers & Pages -> stage-plugin -> Settings -> Build -> Variables and secrets (type Secret),\n" +
          "  click Save, then start a NEW build (push a commit). Worker runtime 'Variables and Secrets' are NOT visible to the build."
        : "  Locally: cp src/secrets.example.ts src/secrets.ts and fill it in."),
  );
  process.exit(1);
}

const raw = Buffer.from(process.env.ENCRYPTION_KEY, "base64");
if (raw.length !== 32) {
  console.error("[secrets] ENCRYPTION_KEY must be 32 random bytes, base64-encoded.");
  process.exit(1);
}

const values = Object.fromEntries([...REQUIRED, ...OPTIONAL].map((k) => [k, process.env[k] ?? ""]));
writeFileSync(
  target,
  `// GENERATED by scripts/write-secrets.mjs from build variables. Git-ignored: never commit.\n` +
    `import type { Secrets } from "./config";\n\n` +
    `export const SECRETS: Secrets = ${JSON.stringify(values, null, 2)};\n`,
);
console.log(`[secrets] wrote src/secrets.ts (${Object.keys(values).join(", ")}${values.DIDAR_INSTALLATION_URL ? "" : "; DIDAR_INSTALLATION_URL empty"})`);
